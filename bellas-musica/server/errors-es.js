// The Spanish for a message, or the message itself when there is none (or the screen is in English).
export function translateError(message, lang, status = 0) {
  const msg = String(message ?? "");
  if (lang !== "es") return msg;
  if (Object.hasOwn(EXACT, msg)) return EXACT[msg];
  const line = /^Line (\d+): (.+)$/.exec(msg); // a guest list line: "Line 3: Phone numbers have 10 digits..."
  if (line) return `Línea ${line[1]}: ${translateError(line[2], lang)}`;
  for (const [re, fn] of PATTERNS) { const m = re.exec(msg); if (m) return fn(m); }
  if (status === 502) return EXACT["Payment provider error"]; // Stripe's own English message
  return msg;
}

// The screen's language: the app sends X-Lang; a link opened elsewhere falls back to the browser's language.
export function requestLang(req) {
  const x = String(req.headers["x-lang"] || "").toLowerCase();
  if (x === "es" || x === "en") return x;
  return /^es\b/i.test(String(req.headers["accept-language"] || "")) ? "es" : "en";
}
